// --- UC8179 quality ---------------------------------------------------------------
// X4 Pro UC8179 4-level quality waveform. The controller expects five separate
// LUT registers, each with the complete 7-phase x 6-byte (42-byte) waveform.
// Keep this panel-specific data beside the other X4 Pro waveforms; HalDisplay only
// owns the upload/activation sequence.
constexpr uint8_t UC8179_QUALITY_LUT_LEN = 42;
// UC8179 gray LUT activation uses the KW data-polarity/CDI value from the
// published 800x480 4-gray sequence. The normal X4 B/W CDI (0x29) selects a
// different transition mapping and collapses the quality pass toward black.
constexpr uint8_t UC8179_QUALITY_CDI = 0x10;
struct Uc8179QualityLut {
  uint8_t cmd;
  uint8_t data[UC8179_QUALITY_LUT_LEN];
};

// --- UC8179 quality (4-level HQ images) -------------------------------------------------
// TRANSLATED FROM THE OEM 4-GREY WAVEFORM, not written by hand.
//
// Source: freeink::kUc8279X3_Xth4 in freeink-sdk/.../lut/Uc8279X3Luts.h - the vendor's own
// four-level table for this controller family, the same one X4ProGrayScale.cpp scales for the
// UC8279 quality path. Only the ENCODING differs between the two controllers, so this is a
// mechanical re-encode, phase for phase:
//     UC8279  7-byte group: [0x01][p0][p1][p2][p3][rp][rp]   p = [2-bit rail][6-bit frames]
//     UC8179  6-byte group: [VS][TP0][TP1][TP2][TP3][RP]     VS = four 2-bit rails packed
// Table index maps onto the tone registers with the EXTREMES SWAPPED but the midtones in
// source order, established on hardware:
//     0 -> 0x20 VCOM, 4 -> 0x21, 2 -> 0x22, 3 -> 0x23, 1 -> 0x24
// Only the extremes are transposed on this panel. Reversing all four at once did fix black
// and the polarity, but it also traded light and dark grey, which left the extremes right
// while local contrast in the midrange ran backwards - light fur reading grey and shading
// coming forward instead of receding.
// The obvious straight order (1 -> 0x21 WW, 4 -> 0x24 BB) is wrong on this panel. Two
// complementary observations pin it: with the quality base un-inverted the render had correct
// polarity but NO BLACK - black pixels select 0x24 and nothing came out - while inverting the
// base routed those same pixels to 0x21 and black appeared, with the whole image reversed.
// Both say 0x21 carries the black-producing waveform and 0x24 the white-producing one.
//
// WHY HAND-WRITTEN TABLES FAILED HERE, so nobody tries again. Several were attempted: a
// black-flash / white-flash / signed-drive ladder, then a one-way ladder from the white clear,
// at 172 and then 240 frames. All produced stipple against paper rather than four tones. The
// reason is structural, not tuning: they used ONE long DC drive per channel, while the OEM
// waveform uses MANY SHORT ALTERNATING phases - 71 frames in 4 groups, and NET ZERO on every
// channel. E-ink particles do not settle into distinct intermediate tones under a single long
// push; the alternation is what places them. No amount of scaling a one-way ladder fixes that.
//
// Frames per phase are 6-bit at the source (max 63). UC8179's TP fields are full bytes, so the
// values transfer unchanged and nothing needs clamping.
//
// If tones need adjusting, scale these phases the way X4ProGrayScale.cpp does - proportionally,
// then walk the net back to zero - rather than editing individual numbers.

/**
 * @file X4ProLuts.h
 * @brief SSD1677 4-level grayscale waveforms for the Xteink X4 Pro.
 *
 * WHY THIS FILE EXISTS
 * --------------------
 * Sticky's board wrapper carries `lut_x4_quality` / `lut_x4_quality_fast`. Neither is
 * usable here, for two independent reasons:
 *
 *  1. They are byte-for-byte IDENTICAL to each other. Sticky's "fast quality" path is
 *     not a faster waveform at all — the only difference between its two code paths is
 *     a delay(120) before the refresh. There was no fast-quality waveform to inherit.
 *  2. Where they DO differ from the X4 factory waveform, the differences are Sticky
 *     module tuning: 60 frames instead of 50, frame-rate 0x44 instead of 0x22, and
 *     VCOM 0x50 instead of 0x30. Sticky's own header says those numbers exist to stop
 *     its module's mid-grays collapsing. Applying another panel's VCOM correction to
 *     this one is how you get muddy or inverted mid-tones.
 *
 * The X4 Pro develops correctly on the panel's own X4-family waveform — see
 * freeink-sdk/docs/xteink-x4pro-support.md#display--ssd1677-800480 ("The plain X4 OTP
 * waveform develops the image — no custom LUT/voltages/PMIC needed"). So both LUTs
 * below start from the X4 FACTORY waveform (freeink::lut_factory_quality), not Sticky's.
 *
 * BYTE LAYOUT (110 bytes, written to SSD1677 command 0x32 + the voltage registers)
 * -------------------------------------------------------------------------------
 *   [  0.. 49]  VS: 5 LUTs x 10 bytes. LUT0=level 00, LUT1=01, LUT2=10, LUT3=11,
 *               LUT4=VCOM. Byte n of a LUT is waveform group n; within a byte the
 *               2-bit fields select the source voltage for phases A,B,C,D
 *               (bits 7:6 = A ... bits 1:0 = D). 00=VSS 01=VSH1 10=VSL 11=VSH2.
 *   [ 50.. 99]  TP/RP: 10 groups x {TPA, TPB, TPC, TPD, RP}. Phase durations in
 *               frames; the group runs (RP+1) times.
 *   [100..104]  Frame rate, one code per group-pair.
 *   [105..109]  VGH, VSH1, VSH2, VSL, VCOM.
 *
 *   Total refresh frames = SUM over groups of (TPA+TPB+TPC+TPD) * (RP+1).
 *
 * The VS block, the frame-rate block and the voltage block are IDENTICAL in both LUTs
 * below and identical to the factory waveform. Only the TP/RP timings differ. That is
 * deliberate: VS defines which rail each grey level is driven to (change it and the
 * levels themselves move), and the voltages are the module's calibration point. Timing
 * is the safe axis to trade against speed.
 */


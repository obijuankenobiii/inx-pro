// --- Tuning, if the panel disagrees --------------------------------------------------
// These are derived from the factory waveform and verified for structure and frame
// arithmetic, but NOT yet confirmed against an X4 Pro panel. If the output is off, tune
// in this order — one change at a time, and only in `lut_quality_fast` first:
//
//   mid-greys too close together / washed out
//       -> VCOM (byte 109, 0x30). Move in single steps. This is the primary control and
//          the one Sticky had to change for its own module (to 0x50).
//   greys correct but too light overall
//       -> VSH1 (byte 106, 0x41), single steps.
//   fast LUT ghosts badly vs quality
//       -> lengthen g0 TPB (byte 51, 0x07) first: it is the longest development phase.
//   fast LUT still too slow
//       -> shorten g1 TPA (byte 55, 0x07) before touching anything else.
//
// Do NOT edit the VS block to fix brightness. It selects rails per phase; changing it
// moves which levels exist rather than how dark they render.


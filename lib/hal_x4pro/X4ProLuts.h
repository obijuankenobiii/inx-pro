// therefore resolves only three tones: white, one grey, black. No plane code can select a
// light grey, because no light-grey waveform exists. It is an anti-aliasing table, not a
// four-tone image table, and it was never meant to separate two greys.
//
// These banks are the stock bytes with ONE change: register 0x22 (BW, which the medium code
